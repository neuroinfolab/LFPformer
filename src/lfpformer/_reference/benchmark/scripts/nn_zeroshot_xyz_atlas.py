#!/usr/bin/env python3
"""Zero-shot NeuroNexus classification: predicted XYZ -> Allen CCF region -> NN 5-class.

NN classes (from upstream paper Neuronexus split): {0=Cortex, 1=CA1, 2=CA2, 3=CA3, 4=DG}.
Our embed_predict_neuronexus.py label-strings call class 0 'UNK' — that's a misnomer,
the actual ground-truth label is Cortex (any non-HPC channel is Cortex by upstream defn).

Pipeline:
  1. Load NN predictions (pred_xyz + region_label + session) — generated by
     embed_predict_neuronexus_ws2.py through Lawrence's IBL-trained
     w2v2 crossneg_240k chandist σ=500 backbone + Gaussian XYZ probe.
  2. For each predicted XYZ (µm CCF), look up Allen structure_id via
     annotation_25.nrrd, walk parent chain. Hierarchy precedence:
        CA1 / CA2 / CA3 / DG  -> NN class 1..4
        Isocortex             -> NN class 0 (Cortex)
        otherwise (TH/HY/STR/MB/HPF-non-subfield/etc.) -> NN class 0 (Cortex)
        out-of-brain (sid=0)  -> NN class 0 (Cortex) as a default
  3. Compare predicted vs true region_label.
  4. Report bal_acc + macro F1 + confusion matrix per XYZ variant, per session.

True zero-shot: backbone never saw NN data, no NN labels used at any stage.
"""
import json
import time
from pathlib import Path

import nrrd
import numpy as np
from sklearn.metrics import balanced_accuracy_score, confusion_matrix, f1_score

ALPHA_ROOT = __import__('lfpformer.paths', fromlist=['legacy_path']).legacy_path('/workspace/ws1/AlphaBrain/Alphabrain_staging')
ANNOTATION_PATH = f"{ALPHA_ROOT}/data/allen_ccf/annotation_25.nrrd"
STRUCTURE_TREE_PATH = f"{ALPHA_ROOT}/data/allen_ccf/structure_tree.json"

import argparse

NN_CLASSES = {0: "Cortex", 1: "CA1", 2: "CA2", 3: "CA3", 4: "DG"}
HPC_ACR_TO_NN = {"CA1": 1, "CA2": 2, "CA3": 3, "DG": 4}
CORTEX_ACR = "Isocortex"  # Allen broad cortex label; everything-else also defaults to Cortex (class 0)

XYZ_VARIANTS = [
    ("raw",                          "predictions.npz",         "pred_xyz"),
    ("raw_refined",                  "predictions_refined.npz", "pred_xyz_raw"),
    ("consensus",                    "predictions_refined.npz", "pred_xyz_consensus"),
    ("depth_regr",                   "predictions_refined.npz", "pred_xyz_depth_regr"),
    ("rigid",                        "predictions_refined.npz", "pred_xyz_rigid"),
    ("weighted",                     "predictions_refined.npz", "pred_xyz_weighted"),
    ("weighted_depth_regr",          "predictions_refined.npz", "pred_xyz_weighted_depth_regr"),
    ("weighted_rigid",               "predictions_refined.npz", "pred_xyz_weighted_rigid"),
]


def log(msg):
    print(f"[{time.strftime('%H:%M:%S')}] {msg}", flush=True)


def build_sid_to_nn(structure_tree_path):
    """For every Allen structure_id, walk ancestors:
       hit CA1/CA2/CA3/DG  -> NN class 1..4
       hit Isocortex       -> NN class 0 (Cortex)
       otherwise           -> NN class 0 (Cortex) — paper's catch-all label.
    """
    with open(structure_tree_path) as f:
        tree = json.load(f)
    parent = {n["id"]: n.get("parent_structure_id") for n in tree}
    acr = {n["id"]: n["acronym"] for n in tree}
    sid_to_nn = {}
    for sid in parent:
        cur = sid
        nn = 0  # default Cortex
        while cur is not None:
            a = acr.get(cur)
            if a in HPC_ACR_TO_NN:
                nn = HPC_ACR_TO_NN[a]
                break
            if a == CORTEX_ACR:
                nn = 0
                break
            cur = parent.get(cur)
        sid_to_nn[sid] = nn
    sid_to_nn[0] = 0  # outside-brain voxels -> Cortex (default)
    return sid_to_nn


def xyz_to_pred_nn(xyz_um, annotation, sid_to_nn):
    """xyz_um (N,3) in CCF µm → NN class via voxel(floor(xyz/25))→sid→NN."""
    voxels = np.floor(xyz_um / 25.0).astype(np.int64)
    shape = np.array(annotation.shape)
    in_bounds = np.all((voxels >= 0) & (voxels < shape), axis=1)
    sids = np.zeros(len(voxels), dtype=np.int64)
    if in_bounds.any():
        v = voxels[in_bounds]
        sids[in_bounds] = annotation[v[:, 0], v[:, 1], v[:, 2]]
    pred_nn = np.zeros(len(voxels), dtype=np.int8)
    unique_sids = np.unique(sids)
    sid_map = {sid: sid_to_nn.get(int(sid), 0) for sid in unique_sids}
    for sid, cls in sid_map.items():
        pred_nn[sids == sid] = cls
    return pred_nn, sids


def fold_to_left(xyz, midline_um=5700.0):
    """Reflect right-hemisphere predictions (ML > midline) to left hemi."""
    out = xyz.astype(np.float32, copy=True)
    right = out[:, 2] > midline_um
    out[right, 2] = 2.0 * midline_um - out[right, 2]
    return out, int(right.sum())


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--variant-dir", required=True,
                    help="Directory containing predictions.npz + predictions_refined.npz")
    ap.add_argument("--exclude-syn03", action="store_true",
                    help="Drop NN_syn_03 (matches upstream 7-session protocol — paper excludes "
                         "NN_syn_03 since it has no GT labels in their pipeline). Outputs to "
                         "zeroshot_xyz_atlas_paper7/ when set, else zeroshot_xyz_atlas/.")
    ap.add_argument("--symmetrize-left", action="store_true",
                    help="Fold ML > 5700 µm to left hemi before atlas lookup. "
                         "Reads predictions_refined_lh.npz; output suffix adds _lh.")
    args = ap.parse_args()
    variant_dir = Path(args.variant_dir)
    suffix = "_lh" if args.symmetrize_left else ""
    out_name = ("zeroshot_xyz_atlas_paper7" if args.exclude_syn03
                else "zeroshot_xyz_atlas") + suffix
    out_dir = variant_dir / out_name
    out_dir.mkdir(exist_ok=True)
    refined_name = ("predictions_refined_lh.npz" if args.symmetrize_left
                    else "predictions_refined.npz")

    log("Loading Allen CCF annotation_25.nrrd ...")
    annotation, _ = nrrd.read(ANNOTATION_PATH)
    log(f"  annotation shape: {annotation.shape}")

    log("Building structure_id → NN class map ...")
    sid_to_nn = build_sid_to_nn(STRUCTURE_TREE_PATH)
    log(f"  {len(sid_to_nn):,} structure_ids covered")

    log(f"Loading NN predictions from {variant_dir} ...")
    raw_npz = np.load(variant_dir / "predictions.npz", allow_pickle=True)
    refined = np.load(variant_dir / refined_name, allow_pickle=True)
    log(f"  refined source: {refined_name}")
    if args.symmetrize_left:
        log("  symmetrize-left: also folding raw pred_xyz from predictions.npz")
        # Materialise into a mutable dict so we can replace the raw-key array
        raw = {k: raw_npz[k] for k in raw_npz.files}
        folded_raw, n_right = fold_to_left(raw["pred_xyz"])
        log(f"    folded {n_right:,}/{len(folded_raw):,} rows in raw key")
        raw["pred_xyz"] = folded_raw
    else:
        raw = raw_npz

    true = raw["region_label"].astype(np.int32)
    sess = np.asarray(raw["session"]).astype(str)

    # Apply NN_syn_03 filter to match upstream paper's 7-session protocol
    keep_idx = np.ones(len(true), dtype=bool)
    if args.exclude_syn03:
        keep_idx = sess != "NN_syn_03"
        log(f"  Excluding NN_syn_03 (paper protocol): "
            f"{(~keep_idx).sum():,} samples dropped, {keep_idx.sum():,} kept")
        true = true[keep_idx]
        sess = sess[keep_idx]
    log(f"  N={len(true):,}  sessions: {sorted(set(sess.tolist()))}")
    log(f"  true class dist: "
        f"{dict(zip(*np.unique(true, return_counts=True)))}")

    # XYZ_VARIANTS uses canonical "predictions_refined.npz" as fname; map it to
    # whichever file we actually loaded (lh-folded or not).
    sources = {"predictions.npz": raw, "predictions_refined.npz": refined}

    summary = {"variants": {}}
    label_names = [NN_CLASSES[i] for i in range(5)]
    sessions_unique = sorted(set(sess.tolist()))

    for name, fname, key in XYZ_VARIANTS:
        log(f"=== Variant: {name} ({fname}::{key}) ===")
        d = sources[fname]
        if key not in d:
            log(f"  MISSING — skipping")
            continue
        xyz = d[key].astype(np.float32)
        pred, sids = xyz_to_pred_nn(xyz, annotation, sid_to_nn)
        # Apply same row filter as labels
        pred = pred[keep_idx]

        results = {}
        # Aggregate metrics (drop UNK true=0 for HPC-only bal_acc as well)
        bal_all = float(balanced_accuracy_score(true, pred))
        f1_all = float(f1_score(true, pred, average="macro"))
        cm_all = confusion_matrix(true, pred, labels=list(range(5))).tolist()

        # HPC-only (drop true class 0 = Cortex)
        keep = true != 0
        bal_hpc = float(balanced_accuracy_score(true[keep], pred[keep]))
        f1_hpc = float(f1_score(true[keep], pred[keep], average="macro",
                                labels=[1, 2, 3, 4], zero_division=0))

        # Per-session metrics (5-class)
        per_sess = {}
        for s in sessions_unique:
            m = sess == s
            per_sess[s] = {
                "n": int(m.sum()),
                "bal_acc_5cls": float(balanced_accuracy_score(true[m], pred[m])),
                "macro_f1_5cls": float(f1_score(true[m], pred[m],
                                                average="macro",
                                                labels=list(range(5)),
                                                zero_division=0)),
            }
            mh = m & keep
            if mh.sum() > 0:
                per_sess[s]["bal_acc_hpc4"] = float(
                    balanced_accuracy_score(true[mh], pred[mh]))
                per_sess[s]["macro_f1_hpc4"] = float(
                    f1_score(true[mh], pred[mh], average="macro",
                             labels=[1, 2, 3, 4], zero_division=0))

        # Class distribution of predictions
        pred_dist = {NN_CLASSES[c]: int(n) for c, n in
                     zip(*np.unique(pred, return_counts=True))}

        log(f"  bal_acc 5cls = {bal_all:.4f}  macro_f1 = {f1_all:.4f}")
        log(f"  bal_acc HPC-only(4cls) = {bal_hpc:.4f}  macro_f1 = {f1_hpc:.4f}")
        log(f"  pred dist: {pred_dist}")

        results = {
            "bal_acc_5cls": bal_all,
            "macro_f1_5cls": f1_all,
            "bal_acc_hpc4": bal_hpc,
            "macro_f1_hpc4": f1_hpc,
            "confusion_matrix": cm_all,
            "label_order": label_names,
            "pred_class_dist": pred_dist,
            "per_session": per_sess,
            "n_total": int(len(true)),
        }
        summary["variants"][name] = results

        # Per-variant detail json
        with open(out_dir / f"zeroshot_{name}.json", "w") as f:
            json.dump(results, f, indent=2)

    # Try to read variant meta.json if present
    src_meta = {}
    if (variant_dir / "meta.json").exists():
        with open(variant_dir / "meta.json") as f:
            src_meta = json.load(f)
    summary["meta"] = {
        "variant_dir": str(variant_dir),
        "source_meta": src_meta,
        "annotation": ANNOTATION_PATH,
        "n_total": int(len(true)),
        "true_class_dist": {NN_CLASSES[c]: int(n) for c, n in
                            zip(*np.unique(true, return_counts=True))},
        "method": "zero-shot: pred_xyz (µm) -> annotation_25 voxel (floor /25) -> structure_id -> walk parents -> {CA1,CA2,CA3,DG} else Cortex",
        "label_map": NN_CLASSES,
    }
    with open(out_dir / "summary.json", "w") as f:
        json.dump(summary, f, indent=2)
    log(f"Saved {out_dir}/summary.json + per-variant jsons")

    # Print neat summary table
    print("\n=== ZERO-SHOT XYZ-ATLAS SUMMARY ===")
    print(f"{'variant':<24} {'bal_acc(5)':>12} {'macroF1(5)':>12} "
          f"{'bal_acc(HPC4)':>14} {'macroF1(HPC4)':>14}")
    for name, _, _ in XYZ_VARIANTS:
        if name not in summary["variants"]:
            continue
        r = summary["variants"][name]
        print(f"{name:<24} {r['bal_acc_5cls']:>12.4f} {r['macro_f1_5cls']:>12.4f} "
              f"{r['bal_acc_hpc4']:>14.4f} {r['macro_f1_hpc4']:>14.4f}")


if __name__ == "__main__":
    main()
